namespace DcsvIo.D2.Messaging.RabbitMq.ErrorCodes.SourceGen;

using System;
using DcsvIo.D2.ErrorCodes.SourceGen;
using Microsoft.CodeAnalysis;

/// <summary>
/// Roslyn incremental source generator that emits the
/// <c>MessagingErrorCodes</c> constants class and the
/// <c>MessagingTransportFailures</c> factory classes into
/// <c>DcsvIo.D2.Messaging.RabbitMq</c>, reading
/// <c>contracts/messaging-error-codes/messaging-error-codes.spec.json</c>
/// through <c>AdditionalFiles</c>. A thin shell over the shared
/// <see cref="ErrorCodesEngine"/>: it owns only this catalog's identity - the
/// target assembly name and this type's fully-qualified name, both of which
/// decide the on-disk generated path - plus its <see cref="CatalogConfig"/>.
/// Every generation step lives in the shared engine. Emits only when the
/// consuming assembly is <c>DcsvIo.D2.Messaging.RabbitMq</c>.
/// </summary>
[Generator]
public sealed class ErrorCodesGenerator : IIncrementalGenerator
{
    private const string _CONSTANTS_BANNER =
        "// -----------------------------------------------------------------------\n" +
        "// <auto-generated>\n" +
        "//   Generated by DcsvIo.D2.Messaging.RabbitMq.ErrorCodes.SourceGen.ErrorCodesGenerator\n" +
        "//   from contracts/messaging-error-codes/messaging-error-codes.spec.json\n" +
        "//   (the source of truth). Manual edits will be lost on rebuild.\n" +
        "// </auto-generated>\n" +
        "// -----------------------------------------------------------------------\n";

    private const string _FAILURES_BANNER = _CONSTANTS_BANNER;

    private const string _CONSTANTS_SUMMARY =
        "/// <summary>\n" +
        "/// Machine-readable <c>d2_error_code</c> string constants surfaced on\n" +
        "/// <see cref=\"DcsvIo.D2.Result.D2Result\"/> failures + RFC 7807\n" +
        "/// <c>ProblemDetails.Extensions[\"d2_error_code\"]</c>.\n" +
        "/// </summary>\n" +
        "/// <remarks>\n" +
        "/// Generated from the spec file, so the codes here and the codes the\n" +
        "/// merged registry publishes come from one source.\n" +
        "/// </remarks>\n";

    private const string _ALL_CODES_DOC =
        "    /// <summary>\n" +
        "    /// All declared <c>LIB_MESSAGING_*</c> codes in spec order. Useful\n" +
        "    /// for closed-set checks and cross-spec consistency tests.\n" +
        "    /// </summary>\n";

    private const string _GET_HTTP_STATUS_DOC =
        "    /// <summary>\n" +
        "    /// Returns the HTTP status code declared in the spec for\n" +
        "    /// <paramref name=\"errorCode\"/>, or <c>500</c> when the code is not\n" +
        "    /// recognized. Every shipped <c>LIB_MESSAGING_*</c> code is in the\n" +
        "    /// table, so the fallback is a defensive default.\n" +
        "    /// </summary>\n" +
        "    /// <param name=\"errorCode\">The messaging error code.</param>\n" +
        "    /// <returns>The HTTP status code.</returns>\n";

    private const string _FAILURES_SUMMARY =
        "/// <summary>\n" +
        "/// Pre-built <see cref=\"D2Result\"/> failures for the messaging transport\n" +
        "/// itself - the cases where the broker was reached and the message still\n" +
        "/// could not be carried.\n" +
        "/// </summary>\n" +
        "/// <remarks>\n" +
        "/// Distinct from <c>DcsvIo.D2.Messaging.MessagingFailures</c>, which covers\n" +
        "/// input validation on the bus surface. Generated from the spec file, so the\n" +
        "/// factory list and the <see cref=\"MessagingErrorCodes\"/> constants cannot\n" +
        "/// disagree.\n" +
        "/// </remarks>\n";

    private const string _GENERIC_FAILURES_SUMMARY =
        "/// <summary>\n" +
        "/// Typed twin of <see cref=\"MessagingTransportFailures\"/> - pre-built\n" +
        "/// <see cref=\"D2Result{T}\"/> messaging-transport failures for callers that\n" +
        "/// need a typed result. Identical method names to the non-generic class; each\n" +
        "/// delegates to the typed <see cref=\"D2Result{T}\"/> base factory, stamping the\n" +
        "/// same <see cref=\"MessagingErrorCodes\"/> constant and message key.\n" +
        "/// </summary>\n" +
        "/// <remarks>\n" +
        "/// <see cref=\"MessagingTransportFailures\"/> (non-generic) and\n" +
        "/// <c>MessagingTransportFailures&lt;T&gt;</c> (generic) are distinct types\n" +
        "/// because their arity differs, exactly as <see cref=\"D2Result\"/> and\n" +
        "/// <see cref=\"D2Result{T}\"/> coexist. Generated from the spec file.\n" +
        "/// </remarks>\n";

    private static readonly CatalogConfig sr_config = new(
        TargetAssemblyName: "DcsvIo.D2.Messaging.RabbitMq",
        SpecFileName: "messaging-error-codes.spec.json",
        RootNamespace: "DcsvIo.D2.Messaging.RabbitMq.Errors",
        ConstantsClassName: "MessagingErrorCodes",
        ConstantsSourceName: "MessagingErrorCodes.g.cs",
        ConstantsBanner: _CONSTANTS_BANNER,
        ConstantsSummary: _CONSTANTS_SUMMARY,
        AllCodesDoc: _ALL_CODES_DOC,
        GetHttpStatusDoc: _GET_HTTP_STATUS_DOC,
        DomainPrefix: "LIB_MESSAGING_",
        Owner: "lib",
        DomainToken: "messaging",
        EmitKebabCase: false,
        EmitFailures: true,
        FailuresClassName: "MessagingTransportFailures",
        FailuresSourceName: "MessagingTransportFailures.g.cs",
        FailuresBanner: _FAILURES_BANNER,
        FailuresSummary: _FAILURES_SUMMARY,
        ValidateCategory: true,
        MalformedSpecId: DiagnosticIds.MalformedSpec,
        DuplicateCodeId: DiagnosticIds.DuplicateCode,
        InvalidHttpStatusId: DiagnosticIds.InvalidHttpStatus,
        InvalidCodeId: null,
        MissingDocId: null,
        UnknownCategoryId: DiagnosticIds.UnknownCategoryEnum,
        DuplicateFactoryNameId: DiagnosticIds.DuplicateFactoryName,
        FactoryHost: FactoryHost.Domain,
        GenericFailuresSourceName: "MessagingTransportFailures.Generic.g.cs",
        GenericFailuresSummary: _GENERIC_FAILURES_SUMMARY);

    /// <summary>
    /// Gets the messaging catalog configuration that this generator passes to
    /// the shared engine. It is exposed so the shared engine emitters can be
    /// driven directly with the real catalog config.
    /// </summary>
    internal static CatalogConfig Config => sr_config;

    /// <inheritdoc/>
    public void Initialize(IncrementalGeneratorInitializationContext context) =>
        ErrorCodesEngine.Run(context, sr_config, ResolveDescriptor);

    private static DiagnosticDescriptor ResolveDescriptor(string id) => id switch
    {
        DiagnosticIds.MalformedSpec => DiagnosticDescriptors.SR_MalformedSpec,
        DiagnosticIds.UnknownCategoryEnum => DiagnosticDescriptors.SR_UnknownCategoryEnum,
        DiagnosticIds.DuplicateCode => DiagnosticDescriptors.SR_DuplicateCode,
        DiagnosticIds.DuplicateFactoryName => DiagnosticDescriptors.SR_DuplicateFactoryName,
        DiagnosticIds.InvalidHttpStatus => DiagnosticDescriptors.SR_InvalidHttpStatus,
        _ => throw new InvalidOperationException(
            $"Unknown EmitDiagnostic descriptor id '{id}'."),
    };
}
